#!/usr/bin/env python3
"""
inject.py — apply the LOS patch layer to mortgage-suite-allinone.html

The two engines are not edited. Three things happen:
  1. the Google Fonts link is swapped for the modern stack
  2. patch.css is appended as the last <style> in <head>, so it wins on
     equal specificity without any !important arms race
  3. patch.js is appended as the last <script> before </body>, so every
     function and store it wraps already exists

Re-runnable: an already-patched file is detected and rebuilt from scratch.
"""
import re, sys, pathlib

SRC   = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/mnt/user-data/uploads/mortgage-suite-allinone.html")
OUT   = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "/mnt/user-data/outputs/mortgage-suite-los.html")
HERE  = pathlib.Path(__file__).parent

FONT_OLD = re.compile(r'<link href="https://fonts\.googleapis\.com/css2\?[^"]*" rel="stylesheet">')
FONT_NEW = ('<link rel="preconnect" href="https://fonts.googleapis.com">\n'
            '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
            '<link href="https://fonts.googleapis.com/css2?'
            'family=Plus+Jakarta+Sans:wght@400;500;600;700;800&'
            'family=Manrope:wght@400;500;600;700;800&'
            'family=JetBrains+Mono:wght@400;500;600&display=swap" rel="stylesheet">')

BEGIN = "<!-- ===== LOS PATCH LAYER — BEGIN (generated by inject.py) ===== -->"
END   = "<!-- ===== LOS PATCH LAYER — END ===== -->"

def main():
    html = SRC.read_text(encoding="utf-8")

    # Rebuilding: strip any layer already present so this is idempotent.
    # Exactly one newline is inserted on each side of a block, so exactly
    # one is taken back off — `\n*` would also eat a newline that belonged
    # to the original document, which shifts the output by a couple of
    # bytes on the first rebuild.
    if BEGIN in html:
        html = re.sub(r"\n?" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?",
                      "", html, flags=re.S)

    # 1a. the document's own fonts
    #
    # FONT_NEW itself still matches FONT_OLD (both are a css2 stylesheet
    # link), so on a re-run against already-patched output the swap fires
    # a second time and appends another pair of preconnect tags. Skip the
    # swap when the modern stack is already in place, and only complain
    # about a missing link when neither is present.
    already_swapped = "family=Plus+Jakarta+Sans" in html
    if not already_swapped:
        html, n = FONT_OLD.subn(FONT_NEW, html, count=1)
        if n == 0:
            raise SystemExit("Could not find the original Google Fonts link — aborting rather than guessing.")

    # 1b. the report / pay stub windows are separate documents written from a
    #     template string, so they carry their own link and their own faces.
    #     They print, so they get the same stack.
    html = html.replace(
        "family=Inter:wght@400;600;700;800&family=JetBrains+Mono:wght@400;600;700",
        "family=Plus+Jakarta+Sans:wght@400;600;700;800&family=Manrope:wght@400;600;700;800")
    html = html.replace("font-family:'Inter',sans-serif", "font-family:'Plus Jakarta Sans',sans-serif")
    html = html.replace("'Segoe UI',Roboto,Inter,Arial,sans-serif",
                        "'Plus Jakarta Sans','Segoe UI',Roboto,Arial,sans-serif")

    # Where the patch files live. Checked in order so that all three ways
    # of invoking this work:
    #   - src/ next to the source HTML (the normal build)
    #   - build/ next to this script (how it was originally written)
    #   - ../src relative to this script (re-running against dist/ output,
    #     which is the idempotent rebuild the README documents)
    candidates = [SRC.parent, HERE, HERE.parent / "src"]
    PATCH_DIR = next((d for d in candidates if (d / "patch.css").exists()), None)
    if PATCH_DIR is None:
        raise SystemExit(
            "Could not find patch.css in any of: "
            + ", ".join(str(d) for d in candidates))

    css = (PATCH_DIR / "patch.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-reno.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v5.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v6.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v7.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v8.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v9.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v10.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v11.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v12.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v13.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v14.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v15.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v16.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v17.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v18.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v19.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v20.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v21.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v22.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v23.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v24.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v25.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v25-1.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v26.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v27.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v28.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v29.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v30.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v31.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v32.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v33.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v34.css").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v35.css").read_text(encoding="utf-8")
    js  = (PATCH_DIR / "patch-scheduler.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-va.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v2.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-docs.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v3.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v4.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v5.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v6.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v7.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v8.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v9.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v10.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v11.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v12.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v13.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v14.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v15.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v16.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v17.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v18.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v19.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v20.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v21.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v22.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v23.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v24.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v25.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v25-1.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v26.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v27.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v28.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v29.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v30.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v31.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v32.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v33.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v34.js").read_text(encoding="utf-8") \
        + "\n\n" + (PATCH_DIR / "patch-v35.js").read_text(encoding="utf-8")

    # 2. stylesheet, last thing in <head>
    if "</head>" not in html:
        raise SystemExit("No </head> found.")
    head_block = f"\n{BEGIN}\n<style>\n{css}\n</style>\n{END}\n"
    html = html.replace("</head>", head_block + "</head>", 1)

    # 3. script, last thing before </body>
    if "</body>" not in html:
        raise SystemExit("No </body> found.")
    body_block = f"\n{BEGIN}\n<script>\n{js}\n</script>\n{END}\n"
    idx = html.rfind("</body>")
    html = html[:idx] + body_block + html[idx:]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(html, encoding="utf-8")
    print(f"wrote {OUT}  ({len(html):,} bytes, source {len(SRC.read_text(encoding='utf-8')):,})")

if __name__ == "__main__":
    main()
